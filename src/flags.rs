#[cfg(test)]
mod tests {
    #[test]
    fn every_regional_flag_has_a_picture() {
        for a in 'a'..='z' {
            for b in 'a'..='z' {
                let code = format!("{a}{b}");
                if let Some(svg) = super::svg(&code) {
                    assert!(svg.contains("viewBox=\"0 0 36 36\""), "{code}");
                }
            }
        }
        for code in ["jp", "tw", "us", "gb", "de", "hk", "sg", "kr", "cn", "fr"] {
            assert!(super::svg(code).is_some(), "{code}");
        }
    }
}
